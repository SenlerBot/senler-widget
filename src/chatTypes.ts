import type {
  SenlerWidgetMessage,
  SenlerWidgetButton,
} from "./messageResult.js";
import type { SenlerWidgetRequestError } from "./clientTypes.js";

export interface SenlerWidgetQueryOptions {
  signal?: AbortSignal;
  timeoutMs?: number;
}
export type SenlerWidgetConnectionState =
  "disconnected" | "connecting" | "connected" | "reconnecting" | "error";
export interface SenlerWidgetDialogSummary {
  id: string;
  title: string;
  avatarUrl?: string | null;
  unreadCount: number;
  revision: number;
}
export interface SenlerWidgetDialogsPage {
  items: SenlerWidgetDialogSummary[];
  hasMore: boolean;
  nextCursor?: string;
  nextOffset?: number;
}
export interface SenlerWidgetMessagesPage {
  /** Oldest first. Merge by eventId and version, never append blindly. */
  items: SenlerWidgetMessage[];
  hasMore: boolean;
  olderCursor?: string;
  newerCursor?: string;
}
export interface SenlerWidgetDialogsOptions extends SenlerWidgetQueryOptions {
  limit?: number;
  before?: string;
  query?: string;
  offset?: number;
}
export interface SenlerWidgetMessagesOptions extends SenlerWidgetQueryOptions {
  dialogId: string;
  limit?: number;
  before?: string;
  after?: string;
}
export interface SenlerWidgetDialogOptions extends SenlerWidgetQueryOptions {
  dialogId: string;
  ref?: string;
}
export interface SenlerWidgetScheduledAction {
  id: string;
  title?: string;
  scheduledAt: string;
  status: "pending" | "processing";
}
export interface SenlerWidgetScheduledActionsPage {
  enabled: boolean;
  items: SenlerWidgetScheduledAction[];
  nextCursor?: string;
}
export interface SenlerWidgetScheduledActionsOptions extends SenlerWidgetQueryOptions {
  dialogId: string;
  cursor?: string;
}
export interface SenlerWidgetTyping {
  id: string;
  name?: string;
  streaming: boolean;
  expiresAt?: string;
}
export interface SenlerWidgetPendingQuestion {
  id: string;
  revision: number;
  text: string;
  createdAt: string;
  sending: boolean;
  attachments: { id: string }[];
}
export interface SenlerWidgetDialogState {
  dialogId: string;
  unreadCount: number;
  revision: number;
  typing: SenlerWidgetTyping[];
  queueEnabled: boolean;
  pending: SenlerWidgetPendingQuestion[];
  pausedReason?: "error" | "limit" | "muted";
}
export interface SenlerWidgetSettingsSnapshot {
  features: { fileUpload: boolean; voiceMessages: boolean; emoji: boolean };
  canStartAgent: boolean;
  creditLimitExhausted: boolean;
  remainingCredits: number | null;
  welcomeText: string;
  welcomeButtons: string[];
}
export interface SenlerWidgetWelcomePreview {
  mode: "centered_text" | "automation_message";
  draftId: string;
  token?: string;
  expiresAt?: string;
  message?: SenlerWidgetMessage;
}
export type SenlerWidgetDialogUpdate =
  | {
      type: "snapshot";
      reason: "initial" | "recovery";
      messages: SenlerWidgetMessagesPage;
      state: SenlerWidgetDialogState;
    }
  | {
      type: "message";
      message: SenlerWidgetMessage;
      /** Stream replaced by this durable message, when it was generated by an agent. */
      streamId?: string;
      /** Original SDK question, when available. */
      requestId?: string;
    }
  | { type: "state"; state: SenlerWidgetDialogState }
  | { type: "deleted"; dialogId: string }
  | {
      type: "chunk";
      dialogId: string;
      /** Original SDK question, if known in this frame; never a generation ID. */
      requestId?: string;
      streamId: string;
      iterationId?: string;
      index: number;
      text: string;
    }
  | {
      type: "streamEnded";
      dialogId: string;
      requestId?: string;
      streamId: string;
      /** May be absent: generation can finish before the message is persisted. */
      eventId?: string;
      status: "completed" | "failed" | "skipped" | "scheduled";
      reason?: string;
      silent?: boolean;
      error?: { code?: string; message: string };
    };
export interface SenlerWidgetDialogSubscriptionOptions extends SenlerWidgetDialogOptions {
  limit?: number;
  /** A snapshot replaces pages on initial load or a gap; lossless reconnects retain pages. */
  onUpdate(update: SenlerWidgetDialogUpdate): void;
  onError(error: SenlerWidgetRequestError): void;
}
export interface SenlerWidgetButtonClickOptions extends SenlerWidgetQueryOptions {
  dialogId: string;
  eventId: string;
  button: SenlerWidgetButton;
  pollSelectedInstanceIds?: string[];
}
export interface SenlerWidgetQueueOptions extends SenlerWidgetDialogOptions {
  questionId: string;
}
export interface SenlerWidgetChatMethods {
  getScheduledActions(
    options: SenlerWidgetScheduledActionsOptions,
  ): Promise<SenlerWidgetScheduledActionsPage>;
  cancelScheduledAction(
    options: SenlerWidgetQueryOptions & { dialogId: string; actionId: string },
  ): Promise<void>;
  getSettings(
    options?: SenlerWidgetQueryOptions,
  ): Promise<SenlerWidgetSettingsSnapshot>;
  getDialogs(
    options?: SenlerWidgetDialogsOptions,
  ): Promise<SenlerWidgetDialogsPage>;
  getMessages(
    options: SenlerWidgetMessagesOptions,
  ): Promise<SenlerWidgetMessagesPage>;
  getDialogState(
    options: SenlerWidgetDialogOptions,
  ): Promise<SenlerWidgetDialogState>;
  getWelcome(
    options?: SenlerWidgetQueryOptions,
  ): Promise<SenlerWidgetWelcomePreview>;
  subscribeDialog(options: SenlerWidgetDialogSubscriptionOptions): () => void;
  /** Marks the dialog read when the host actually displays its messages. */
  markRead(options: SenlerWidgetDialogOptions): Promise<void>;
  setTyping(
    options: SenlerWidgetDialogOptions & { typing: boolean },
  ): Promise<void>;
  clickButton(options: SenlerWidgetButtonClickOptions): Promise<void>;
  updateQueuedQuestion(
    options: SenlerWidgetQueueOptions & { revision: number; text: string },
  ): Promise<void>;
  cancelQueuedQuestion(options: SenlerWidgetQueueOptions): Promise<void>;
  sendQueuedQuestion(options: SenlerWidgetQueueOptions): Promise<void>;
}

/** Private transport contract, shared by the SDK and its authenticated iframe. */
export interface WidgetChatCommands {
  getScheduledActions: {
    input: { dialogId: string; cursor?: string };
    output: SenlerWidgetScheduledActionsPage;
  };
  cancelScheduledAction: {
    input: { dialogId: string; actionId: string };
    output: void;
  };
  getSettings: {
    input: Record<string, never>;
    output: SenlerWidgetSettingsSnapshot;
  };
  getDialogs: {
    input: Omit<SenlerWidgetDialogsOptions, keyof SenlerWidgetQueryOptions>;
    output: SenlerWidgetDialogsPage;
  };
  getMessages: {
    input: Omit<SenlerWidgetMessagesOptions, keyof SenlerWidgetQueryOptions>;
    output: SenlerWidgetMessagesPage;
  };
  getDialogState: {
    input: { dialogId: string; ref?: string };
    output: SenlerWidgetDialogState;
  };
  getWelcome: {
    input: Record<string, never>;
    output: SenlerWidgetWelcomePreview;
  };
  markRead: { input: { dialogId: string }; output: void };
  setTyping: { input: { dialogId: string; typing: boolean }; output: void };
  clickButton: {
    input: Omit<SenlerWidgetButtonClickOptions, keyof SenlerWidgetQueryOptions>;
    output: void;
  };
  updateQueuedQuestion: {
    input: {
      dialogId: string;
      questionId: string;
      revision: number;
      text: string;
    };
    output: void;
  };
  cancelQueuedQuestion: {
    input: { dialogId: string; questionId: string };
    output: void;
  };
  sendQueuedQuestion: {
    input: { dialogId: string; questionId: string };
    output: void;
  };
}
export type WidgetChatCommand = {
  [K in keyof WidgetChatCommands]: {
    method: K;
    input: WidgetChatCommands[K]["input"];
  };
}[keyof WidgetChatCommands];
export type WidgetChatNotification =
  | { type: "connectionChanged"; state: SenlerWidgetConnectionState }
  | { type: "dialogsChanged" }
  | { type: "settingsChanged" };
